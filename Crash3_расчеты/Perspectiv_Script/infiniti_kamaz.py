def build_k_norm(k_rel: np.ndarray) -> np.ndarray:
    """Нормировка коэффициентов жесткости."""
    k_rel = np.asarray(k_rel, dtype=float)
    mask = k_rel > 0.0
    if not np.any(mask):
        # Если вся матрица нули, возвращаем нули, чтобы не упало с ошибкой
        return np.zeros_like(k_rel)
    mean_pos = float(k_rel[mask].mean())
    k_norm = np.zeros_like(k_rel)
    k_norm[mask] = k_rel[mask] / mean_pos
    return k_norm


def crash3_energy_matrix(
    c: np.ndarray,
    k_rel: np.ndarray | None,
    A_global: float,
    B_global: float,
    c0: float,
    cell_width: float,
) -> np.ndarray:
    """Расчет энергии E_ij = ширина * интеграл силы."""
    c = np.asarray(c, dtype=float)
    c_eff = np.maximum(0.0, c - c0)

    if k_rel is None:
        Aij = np.full_like(c_eff, A_global)
        Bij = np.full_like(c_eff, B_global)
    else:
        k_norm = build_k_norm(np.asarray(k_rel, dtype=float))
        Aij = A_global * k_norm
        Bij = B_global * k_norm

    # E = w * (A*c^2/2 + B*c^3/3)
    E = cell_width * (0.5 * Aij * c_eff**2 + (1.0 / 3.0) * Bij * c_eff**3)
    return E

def analyze_airbag_deployment(ees_kmh: float) -> str:
    """Вердикт по SRS на основе EES."""
    if ees_kmh < 15.0:
        return "НЕТ (Ниже порога 'Must Not Fire' ~15 км/ч)"
    elif 15.0 <= ees_kmh < 25.0:
        return "СЕРАЯ ЗОНА (Вероятность 50/50, зависит от импульса)"
    elif ees_kmh >= 25.0:
        return "ДА (Выше порога 'Must Fire' ~25 км/ч)"
    return "Неопределенно"


