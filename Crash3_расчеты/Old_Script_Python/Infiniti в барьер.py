# -----------------------------
# Функции расчёта
# -----------------------------
def e_unit(c_val: np.ndarray) -> np.ndarray:
    """
    Энергия на единицу ширины (CRASH3-полином):
    e = A/2 * c^2 + B/3 * c^3
    """
    return 0.5 * A * c_val**2 + (1.0/3.0) * B * c_val**3

def calc_cell_energy(c_matrix: np.ndarray, k_matrix: np.ndarray, use_c0: bool = True):
    """
    Возвращает матрицу энергий по ячейкам и суммарную энергию.
    Если use_c0=True, используем c* = max(0, c - c0).
    """
    if use_c0:
        c_eff = np.clip(c_matrix - c0, 0, None)
    else:
        c_eff = c_matrix.copy()

    E_cell = k_matrix * dw * e_unit(c_eff)
    E_total = float(E_cell.sum())
    return E_cell, E_total

def ees_from_energy(E_total: float, mass: float):
    """EES по энергии: v = sqrt(2E/m)."""
    v_ms = math.sqrt(2 * E_total / mass) if E_total > 0 else 0.0
    v_kmh = v_ms * 3.6
    return v_ms, v_kmh

