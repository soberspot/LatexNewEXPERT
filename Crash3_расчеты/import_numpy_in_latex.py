import numpy as np

def save_numpy_to_latex_with_indices(arr, filename="matrix_with_numbers.tex"):
    """
    Сохраняет 2D numpy массив в файл .tex с нумерацией строк.
    """
    rows, cols = arr.shape

    # +1 к количеству колонок для номера строки
    latex_code = [
        r"\begin{table}[h!]",
        r"    \centering",
        r"    \caption{Матрица деформации с нумерацией строк}",
        r"    \label{tab:c_inf_matrix}",
        r"    \resizebox{\textwidth}{!}{%",
        r"        \begin{tabular}{|c|" + "c|" * cols + "}", # Добавлена первая колонка 'c|'
        r"        \hline",
        # Опционально: заголовок (№ и индексы колонок)
        "        № & " + " & ".join([f"j={j+1}" for j in range(cols)]) + r" \\ \hline"
    ]

    # Заполняем строки данными
    for i, row in enumerate(arr, start=1):
        # Форматируем числа: 2 знака после запятой
        row_values = [f"{x:.2f}" for x in row]

        # Добавляем номер строки i в начало
        row_str = f"{i} & " + " & ".join(row_values)
        latex_code.append(f"        {row_str} \\\\ \\hline")

    # Закрываем теги
    latex_code.extend([
        r"        \end{tabular}",
        r"    }",
        r"\end{table}"
    ])

    full_content = "\n".join(latex_code)

    with open(filename, "w", encoding="utf-8") as f:
        f.write(full_content)

    print(f"Файл {filename} успешно создан.")

